-- ===== CLASE 013: SERIAL E IDENTITY =====

/*
OBJETIVO
Hacer que PostgreSQL genere automáticamente un número único y creciente
para cada fila nueva, sin que tengas que escribirlo a mano.

CONCEPTO
Una columna autoincremental toma su valor de una secuencia, que es un contador
interno administrado por PostgreSQL. Hay dos formas de declararla:
SERIAL (la forma clásica de PostgreSQL) y IDENTITY (la forma estándar de SQL,
recomendada en tablas nuevas). Ninguna de las dos convierte la columna en
clave primaria: eso se declara aparte con PRIMARY KEY (clase 012).

PARA QUÉ SIRVE
1) Asignar un identificador a cada pedido, factura o ticket sin repetirlo.
2) Crear la clave primaria de tablas de dimensiones (clientes, productos,
   sucursales) que luego se enlazan con otras tablas.
3) Numerar eventos o registros de un log en el orden en que llegan.

SINTAXIS GENERAL

   nombre_columna  SERIAL
   nombre_columna  INTEGER GENERATED ALWAYS AS IDENTITY
   nombre_columna  BIGINT  GENERATED BY DEFAULT AS IDENTITY

   - SERIAL: atajo que crea una columna INTEGER, NOT NULL, con su secuencia.
   - SMALLSERIAL / SERIAL / BIGSERIAL: igual, pero la columna es
     SMALLINT (hasta 32.767), INTEGER (hasta 2.147.483.647) o BIGINT.
   - GENERATED ... AS IDENTITY: la columna debe ser SMALLINT, INTEGER o BIGINT.
   - ALWAYS: PostgreSQL siempre genera el valor y rechaza los manuales.
   - BY DEFAULT: PostgreSQL genera el valor, pero permite escribir uno manual.

NOTA: en los ejemplos de teoría se usa INSERT, que se estudia en la clase 021.
Por ahora léelo como "agrega una fila con estos valores". Los ejemplos están
comentados para que no ensucien tu base: si quieres probarlos, descoméntalos
después de ejecutar el SETUP (quedarán dentro del esquema practica).

------------------------------------------------------------------
EJEMPLO 1: SERIAL genera el id solo
------------------------------------------------------------------
Se omite la columna id_libro al agregar filas y PostgreSQL la completa.

-- CREATE TABLE libros (
--     id_libro SERIAL PRIMARY KEY,
--     titulo   VARCHAR(60) NOT NULL
-- );
--
-- INSERT INTO libros (titulo)
-- VALUES ('Rayuela'), ('Ficciones'), ('Aura');
--
-- SELECT * FROM libros;

Resultado esperado:

   id_libro | titulo
   ---------+-----------
          1 | Rayuela
          2 | Ficciones
          3 | Aura

------------------------------------------------------------------
EJEMPLO 2: GENERATED ALWAYS rechaza valores manuales
------------------------------------------------------------------
-- CREATE TABLE salas_cine (
--     id_sala INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
--     nombre  VARCHAR(30) NOT NULL
-- );
--
-- INSERT INTO salas_cine (id_sala, nombre)
-- VALUES (10, 'Sala Norte');

Resultado esperado: la instrucción falla.

   ERROR: cannot insert a non-DEFAULT value into column "id_sala"
   Detail: Column "id_sala" is an identity column defined as GENERATED ALWAYS.

Para que funcione, se omite id_sala en el INSERT y PostgreSQL asigna el 1.

------------------------------------------------------------------
EJEMPLO 3: BY DEFAULT permite valores manuales, pero el contador no se entera
------------------------------------------------------------------
-- CREATE TABLE talleres (
--     id_taller INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
--     nombre    VARCHAR(30) NOT NULL
-- );
--
-- INSERT INTO talleres (id_taller, nombre) VALUES (2, 'Taller Manual');
-- INSERT INTO talleres (nombre) VALUES ('Taller A');   -- recibe el 1
-- INSERT INTO talleres (nombre) VALUES ('Taller B');   -- intenta usar el 2
--
-- SELECT * FROM talleres;

Resultado esperado: el tercer INSERT falla porque el 2 ya está ocupado.

   ERROR: duplicate key value violates unique constraint "talleres_pkey"
   Detail: Key (id_taller)=(2) already exists.

El SELECT final muestra solo dos filas:

   id_taller | nombre
   ----------+---------------
           2 | Taller Manual
           1 | Taller A

Aunque falló, la secuencia ya consumió el 2: la siguiente fila válida recibirá
el 3 y el número 2 de la secuencia queda perdido. Los huecos son normales.

ERRORES Y BUENAS PRÁCTICAS
- Error: escribir un id manual en una columna ALWAYS. Mensaje:
  "cannot insert a non-DEFAULT value into column". Causa: ALWAYS prohíbe
  cualquier valor que no sea el generado.
- Error: "duplicate key value violates unique constraint" tras insertar ids
  a mano en una columna BY DEFAULT. Causa: la secuencia no sabe qué números
  usaste y termina generando uno ya ocupado.
- Error: "identity column type must be smallint, integer, or bigint" al declarar
  IDENTITY sobre VARCHAR, NUMERIC u otro tipo. Causa: solo los enteros pueden
  autoincrementarse.
- Buena práctica: en tablas nuevas prefiere GENERATED ALWAYS AS IDENTITY y
  agrégale siempre PRIMARY KEY, porque ni SERIAL ni IDENTITY garantizan que
  los valores no se repitan por sí solos.
- Buena práctica: elige el tipo según el volumen esperado (BIGINT para tablas
  que crecerán mucho) y no esperes ids consecutivos: no se reutilizan.
*/


